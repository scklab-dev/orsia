"""Isolated SASKTRAN2 worker for the five-band notebook (no Orsia imports).

Input arrays are bottom-to-top layer quantities, cm-1 coordinates and radiance
or irradiance densities per cm-1. Thin interface ramps approximate discontinuous
layers; their width decreases with cells. This is a comparison adapter, not truth.
"""

import argparse
import hashlib
import importlib.metadata
import json
import os
import platform
import sys
from pathlib import Path
from time import perf_counter

import numpy as np


def backend_identity() -> dict:
    """Fingerprint the isolated runtime and installed files, after native imports.

    Hash installed distribution contents (including bundled native libraries),
    excluding generated bytecode. Recheck on every cache access so package
    upgrades and in-place installed-source edits invalidate existing references.
    """
    import sasktran2  # type: ignore[import-not-found]  # noqa: F401

    packages = {}
    for distribution in importlib.metadata.distributions():
        digest = hashlib.sha256()
        for item in sorted(distribution.files or [], key=str):
            path = Path(str(distribution.locate_file(item)))
            if path.suffix == ".pyc" or not path.is_file():
                continue
            digest.update(str(item).encode())
            with path.open("rb") as handle:
                digest.update(hashlib.file_digest(handle, "sha256").digest())
        packages[distribution.metadata["Name"]] = {
            "version": distribution.version,
            "files_sha256": digest.hexdigest(),
        }
    executable = Path(sys.executable).resolve()
    with executable.open("rb") as handle:
        executable_sha256 = hashlib.file_digest(handle, "sha256").hexdigest()
    return {
        "python": sys.version,
        "sasktran2": importlib.metadata.version("sasktran2"),
        "gil_enabled": sys._is_gil_enabled(),
        "executable": str(executable),
        "executable_sha256": executable_sha256,
        "prefix": sys.prefix,
        "platform": platform.platform(),
        "machine": platform.machine(),
        "packages": packages,
        "thread_environment": {
            name: os.environ.get(name)
            for name in (
                "OMP_NUM_THREADS",
                "OPENBLAS_NUM_THREADS",
                "MKL_NUM_THREADS",
                "NUMEXPR_NUM_THREADS",
                "VECLIB_MAXIMUM_THREADS",
            )
        },
    }


def calculate(path: Path, *, cells: int, streams: int, runs: int = 3) -> dict:
    """Solve materialized shared layers; never acquire data or install packages."""
    import sasktran2 as sk  # type: ignore[import-not-found]

    with np.load(path, allow_pickle=False) as data:
        arrays = {key: data[key].copy() for key in data.files}
    edges = arrays["height_m"]
    widths = np.diff(edges)
    # Keep constant interiors and symmetric, narrow interface ramps.
    nodes = np.concatenate(
        [
            np.linspace(a + d / (cells * 10000), b - d / (cells * 10000), cells)
            for a, b, d in zip(edges[:-1], edges[1:], widths, strict=True)
        ]
    )
    nodes = np.concatenate(([edges[0]], nodes, [edges[-1]]))
    layer = np.clip(np.searchsorted(edges, nodes, side="right") - 1, 0, len(widths) - 1)
    axis = arrays["wavenumbers_cm1"]
    thermal = bool(arrays["thermal"])
    config = sk.Config()
    config.num_threads = 1
    config.num_stokes = 1
    config.num_sza = 1
    config.num_streams = streams
    config.num_singlescatter_moments = streams
    config.delta_m_scaling = False
    config.output_los_optical_depth = True
    config.single_scatter_source = (
        sk.SingleScatterSource.NoSource if thermal else sk.SingleScatterSource.Exact
    )
    config.multiple_scatter_source = (
        sk.MultipleScatterSource.NoSource if thermal else sk.MultipleScatterSource.DiscreteOrdinates
    )
    if thermal:
        config.emission_source = sk.EmissionSource.Standard
    mu0, muv = float(arrays["mu0"]), float(arrays["muv"])
    geometry = sk.Geometry1D(
        mu0,
        0.0,
        6372000.0,
        nodes,
        sk.InterpolationMethod.LinearInterpolation,
        sk.GeometryType.PlaneParallel,
    )
    viewing = sk.ViewingGeometry()
    viewing.add_ray(
        sk.GroundViewingSolar(
            cos_sza=mu0,
            relative_azimuth=0.0,
            cos_viewing_zenith=muv,
            observer_altitude_m=edges[-1] + 1.0,
        )
    )
    atmosphere = sk.Atmosphere(
        geometry, config, wavelengths_nm=1e7 / axis, calculate_derivatives=False
    )
    absorption = arrays["absorption_depth"]
    scattering = arrays["rayleigh_depth"]
    if thermal and np.any(scattering):
        raise ValueError("This notebook's thermal control excludes scattering")
    total = absorption + scattering
    atmosphere.storage.total_extinction[:] = (total / widths[:, None])[layer]
    atmosphere.storage.ssa[:] = np.divide(
        scattering, total, out=np.zeros_like(total), where=total > 0
    )[layer]
    atmosphere.storage.leg_coeff[:] = 0.0
    atmosphere.storage.leg_coeff[0] = 1.0
    atmosphere.storage.leg_coeff[2] = 0.5
    # Solar storage is a numeric normalization; supply per-nm density here.
    jacobian = 1e7 / axis**2
    atmosphere.storage.solar_irradiance[:] = arrays["irradiance"] / jacobian
    atmosphere.surface.albedo[:] = arrays["albedo"]
    reflected_boundary = np.zeros_like(axis)
    if thermal:
        atmosphere.temperature_k = arrays["temperature_k"][layer]
        sk.constituent.ThermalEmission().add_to_atmosphere(atmosphere)
        sk.constituent.SurfaceThermalEmission(
            temperature_k=float(arrays["surface_temperature_k"]),
            emissivity=arrays["emissivity"],
        ).add_to_atmosphere(atmosphere)
        # NoSource thermal transport does not reflect atmospheric emission.
        # Supply the Lambertian boundary explicitly, independently of Orsia.
        # This is absorption-only LTE with no incident radiation at the top.
        reflected_boundary = thermal_reflected_boundary(arrays)
        atmosphere.surface.emission[:] += reflected_boundary / jacobian
    if runs < 1:
        raise ValueError("runs must be >= 1")
    engine = sk.Engine(config, geometry, viewing)
    start = perf_counter()
    result = engine.calculate_radiance(atmosphere)
    first_seconds = perf_counter() - start
    seconds = []
    for _ in range(runs):
        start = perf_counter()
        result = engine.calculate_radiance(atmosphere)
        seconds.append(perf_counter() - start)
    import importlib.metadata
    import sys

    return {
        "timing": {
            "first_seconds": first_seconds,
            "seconds": seconds,
            "median_seconds": float(np.median(seconds)),
            "scope": (
                "calculate_radiance; prepared atmosphere and reused engine; "
                "excludes thermal boundary adapter"
            ),
        },
        "radiance": (result["radiance"].values.ravel() * jacobian).tolist(),
        "los_optical_depth": result["los_optical_depth"].values.ravel().tolist(),
        "cells": cells,
        "streams": streams,
        "sasktran2": importlib.metadata.version("sasktran2"),
        "python": sys.version,
        "gil_enabled": sys._is_gil_enabled(),
        "thermal_surface_coupling": "explicit_lambertian_boundary" if thermal else "native_solar",
        "reflected_boundary_radiance": reflected_boundary.tolist() if thermal else None,
    }


def thermal_reflected_boundary(
    arrays: dict, *, angular_order: int = 128
) -> np.ndarray[tuple[int, ...], np.dtype[np.float64]]:
    """Reflected downward LTE radiance at ground, W m-2 sr-1 per cm-1.

    Independent Gauss-Legendre hemispheric integration of shared constant
    layers, bottom to top. The returned owned array is a boundary source,
    not a TOA correction: SASKTRAN2 propagates it through the atmosphere.
    Only valid for absorption-only transport and a Lambertian surface.
    """
    axis = arrays["wavenumbers_cm1"]
    tau = arrays["absorption_depth"]
    temperature = arrays["temperature_k"]
    frequency = 100 * 299792458.0 * axis
    planck = (
        2
        * 6.62607015e-34
        * frequency[None, :] ** 3
        / 299792458.0**2
        / np.expm1(6.62607015e-34 * frequency[None, :] / (1.380649e-23 * temperature[:, None]))
        * 100
        * 299792458.0
    )
    nodes, weights = np.polynomial.legendre.leggauss(angular_order)
    mu, weights = (nodes + 1) / 2, weights / 2
    downward = np.zeros((angular_order, len(axis)))
    for depth, source in zip(tau[::-1], planck[::-1], strict=True):
        transmission = np.exp(-depth[None, :] / mu[:, None])
        downward = downward * transmission + source * (-np.expm1(-depth[None, :] / mu[:, None]))
    return 2 * arrays["albedo"] * np.sum(weights[:, None] * mu[:, None] * downward, axis=0)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path, nargs="?")
    parser.add_argument("--identity", action="store_true")
    parser.add_argument("--cells", type=int, default=16)
    parser.add_argument("--streams", type=int, default=32)
    parser.add_argument("--runs", type=int, default=3)
    args = parser.parse_args()
    if args.identity:
        print(json.dumps(backend_identity(), allow_nan=False))
        sys.exit(0)
    if args.input is None:
        parser.error("input is required for a solve")
    if args.cells < 2 or args.streams < 4 or args.streams % 2:
        parser.error("cells >= 2 and even streams >= 4 required")
    print(
        json.dumps(
            calculate(args.input, cells=args.cells, streams=args.streams, runs=args.runs),
            allow_nan=False,
        )
    )
